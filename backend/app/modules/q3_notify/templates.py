def render(kind: str, variables: dict[str, str]) -> str:
    """미리보기용: 템플릿 원문에 값을 채운다 (실제 발송은 솔라피가 채움)."""
    text = TEMPLATES[kind]["text"]
    for k, v in variables.items():
        text = text.replace(f"#{{{k}}}", v)
    return text
